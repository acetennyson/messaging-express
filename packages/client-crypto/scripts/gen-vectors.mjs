// Regenerates test/vectors/vectors.json from FIXED inputs (keys, nonces, salts), so the file is reproducible and reviewable.
// Run after `npm run build`:  node scripts/gen-vectors.mjs
// By default this only CHECKS that the file is reproduced; it writes only with --write.
// NEVER regenerate to "fix" a failing test: a change here means the wire format changed, which needs a new version byte (see WIRE_FORMAT.md).
// scripts/crosscheck.py verifies this file with independent implementations (libsodium via PyNaCl, `cryptography`, argon2-cffi).
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { nobleProvider as p, wrapConversationKey, encryptMessage, createBackup, toBase64Url, pad, wrapInfo, messageAad, backupAad, encryptAttachment } from '../dist/index.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const seq = (n, s = 0) => Uint8Array.from({ length: n }, (_, i) => (s + i) & 0xff);
const hex = (b) => Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');

const ids = {
  conversationId: 'c0000000-0000-4000-8000-000000000001',
  senderUserId: 'u0000000-0000-4000-8000-0000000000a1',
  deviceA: 'd0000000-0000-4000-8000-0000000000a1',
  deviceB: 'd0000000-0000-4000-8000-0000000000b1',
};
const privA = seq(32, 0x10), privB = seq(32, 0x50);
const pubA = p.publicKeyFor(privA), pubB = p.publicKeyFor(privB);
const ck = seq(32, 0xc0);

const wrapCtx = { conversationId: ids.conversationId, keyVersion: 3, senderDeviceId: ids.deviceA, recipientDeviceId: ids.deviceB };
const wrapNonce = seq(24, 0x01);
const wrapBlob = wrapConversationKey(ck, wrapCtx, privA, pubB, { nonce: wrapNonce });
const wrapKey = p.hkdf(p.ecdh(privA, pubB), wrapInfo(wrapCtx), 32);

const msgCtx = { conversationId: ids.conversationId, keyVersion: 3, senderId: ids.senderUserId };
const OVERHEAD = JSON.stringify({ v: 1, t: '', a: [] }).length;
const texts = [
  ['empty', ''],
  ['short', 'hello'],
  ['unicode', 'héllo wörld 🌍 こんにちは'],
  // sized so the UNPADDED payload JSON is exactly 63, 64 and 65 bytes: 63 fits one block, 64 needs the 0x80 marker so it takes two, 65 takes two
  ['payload-63', 'x'.repeat(63 - OVERHEAD)],
  ['payload-64', 'x'.repeat(64 - OVERHEAD)],
  ['payload-65', 'x'.repeat(65 - OVERHEAD)],
  ['long', 'The quick brown fox jumps over the lazy dog. '.repeat(10)],
];
const messages = texts.map(([name, text], i) => {
  const nonce = seq(24, 0x20 + i);
  const content = { text, attachments: name === 'short' ? [{ kind: 'file', id: 'att-1', size: 12 }] : [] };
  const blob = encryptMessage(content, ck, msgCtx, { nonce });
  const payloadJson = JSON.stringify({ v: 1, t: content.text, a: content.attachments });
  return { name, text: content.text, attachments: content.attachments, nonce: hex(nonce), payloadJson, paddedPayloadHex: hex(pad(new TextEncoder().encode(payloadJson))), blob };
});

const backupInput = { deviceId: ids.deviceA, privateKey: privA };
const backupPass = 'correct horse battery staple';
const backupParams = { m: 1024, t: 1, p: 1 };
const backupSalt = seq(16, 0x70), backupNonce = seq(24, 0x90);
const backup = await createBackup(backupInput, backupPass, backupParams, { salt: backupSalt, nonce: backupNonce });

const attFileKey = seq(32, 0x30), attStreamNonce = seq(16, 0xa0);
const attPattern = (n) => Uint8Array.from({ length: n }, (_, i) => (i * 7 + 3) & 255);
const attachments = [];
for (const size of [0, 1, 65535, 65536, 65537, 131072, 200000]) {
  const { ciphertext } = await encryptAttachment(attPattern(size), { name: 'v.bin', type: 'application/octet-stream' }, { fileKey: attFileKey, streamNonce: attStreamNonce });
  attachments.push({ size, chunks: Math.max(1, Math.ceil(size / 65536)), ciphertextLength: ciphertext.length, ciphertextSha256: createHash('sha256').update(ciphertext).digest('hex'), ...(size <= 1 ? { ciphertextHex: hex(ciphertext) } : {}) });
}

const out = {
  _comment: 'Frozen test vectors for WIRE_FORMAT.md version 0x01. Generated by scripts/gen-vectors.mjs from fixed inputs; verified independently by scripts/crosscheck.py.',
  ids,
  keys: { privA: hex(privA), pubA: hex(pubA), privB: hex(privB), pubB: hex(pubB), conversationKey: hex(ck) },
  wrap: { ctx: wrapCtx, nonce: hex(wrapNonce), info: new TextDecoder().decode(wrapInfo(wrapCtx)), derivedKey: hex(wrapKey), blob: wrapBlob, blobLength: 73 },
  messageContext: msgCtx,
  messageAad: new TextDecoder().decode(messageAad(msgCtx)),
  messages,
  backup: { passphrase: backupPass, params: backupParams, salt: hex(backupSalt), nonce: hex(backupNonce), payload: { deviceId: backupInput.deviceId, privateKey: hex(privA) }, aad: new TextDecoder().decode(backupAad(backup.kdf)), blob: backup.blob, kdf: backup.kdf },
  attachment: { fileKey: hex(attFileKey), streamNonce: hex(attStreamNonce), aad: 'mx-e2ee-v1|att', plaintext: 'byte i = (i * 7 + 3) mod 256', cases: attachments },
  base64url: [[], [0], [0, 1], [0, 1, 2], [255, 254, 253, 252], [251, 255, 191]].map((a) => ({ hex: hex(Uint8Array.from(a)), b64u: toBase64Url(Uint8Array.from(a)) })),
};
const file = path.join(here, '..', 'test', 'vectors', 'vectors.json'), text = JSON.stringify(out, null, 2) + '\n';
if (process.argv.includes('--write')) { fs.writeFileSync(file, text); console.log('wrote test/vectors/vectors.json'); }
else if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) console.log('vectors.json is reproduced byte for byte (nothing written).');
else { console.error('vectors.json DIFFERS from what this build produces. The file is frozen: a difference means the wire format changed. Nothing was written. (Pass --write only for a deliberate format version bump.)'); process.exit(1); }
